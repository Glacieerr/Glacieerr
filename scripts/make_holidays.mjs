// Spring Festival and Mid-Autumn dates (idea #150), worked out with Node's ICU Chinese
// calendar and written as the same table to two places:
//   scripts/festivals.py   the README art looks the day up here (the nightly job needs no Node for it)
//   live/holidays.mjs      for the interactive page and the live banner
// Every year is compared with the published dates (PUBLISHED below). ICU's calendar is not always
// right: when a new moon falls within minutes of midnight in Beijing it can start the month a day
// early or late (2027 and 2030 here), so where the two disagree the published date is used and
// the script says so. A year without a published date stops the script.
//   node scripts/make_holidays.mjs            write both files
//   node scripts/make_holidays.mjs --check    recompute and compare with both files, write nothing
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const FIRST = 2024;
const LAST = 2035;
const PY = fileURLToPath(new URL('./festivals.py', import.meta.url));
const MJS = fileURLToPath(new URL('../live/holidays.mjs', import.meta.url));

// Published dates, read on 2026-11-14:
//   Wikipedia, "Chinese New Year" (table of dates, 2026 to 2037; infobox for 2025)
//   Wikipedia, "Mid-Autumn Festival" (Dates section, 2026 to 2030; infobox for 2025)
//   Hong Kong Observatory, Gregorian-Lunar calendar conversion tables (www.hko.gov.hk/en/gts/
//   time/calendar/text/files/T<year>e.txt) for 2024, 2027, 2030, 2031, 2032, 2033, 2034 and 2035.
//   2033 is the year of the "2033 problem": its leap month is the 11th, so the 8th month starts
//   on 2033-08-25 and Mid-Autumn is 2033-09-08.
const PUBLISHED = {
  spring: {
    2024: '2024-02-10', 2025: '2025-01-29', 2026: '2026-02-17', 2027: '2027-02-06', 2028: '2028-01-26',
    2029: '2029-02-13', 2030: '2030-02-03', 2031: '2031-01-23', 2032: '2032-02-11', 2033: '2033-01-31',
    2034: '2034-02-19', 2035: '2035-02-08',
  },
  midAutumn: {
    2024: '2024-09-17', 2025: '2025-10-06', 2026: '2026-09-25', 2027: '2027-09-15', 2028: '2028-10-03',
    2029: '2029-09-22', 2030: '2030-09-12', 2031: '2031-10-01', 2032: '2032-09-19', 2033: '2033-09-08',
    2034: '2034-09-27', 2035: '2035-09-16',
  },
};

const iso = (ms) => new Date(ms).toISOString().slice(0, 10);

/** Every Gregorian day of a year with its Chinese month ("8", or "6bis" for a leap month) and day. */
function chineseDays(year) {
  const f = new Intl.DateTimeFormat('en-u-ca-chinese', { timeZone: 'UTC', year: 'numeric', month: 'numeric', day: 'numeric' });
  if (f.resolvedOptions().calendar !== 'chinese') throw new Error('this Node has no ICU Chinese calendar');
  const out = [];
  for (let ms = Date.UTC(year, 0, 1, 12); new Date(ms).getUTCFullYear() === year; ms += 86400000) {
    const p = Object.fromEntries(f.formatToParts(ms).map((x) => [x.type, x.value]));
    out.push({ date: iso(ms), month: p.month, day: Number(p.day) });
  }
  return out;
}

function compute() {
  const spring = {};
  const midAutumn = {};
  for (let y = FIRST; y <= LAST; y++) {
    const days = chineseDays(y);
    const sf = days.find((d) => d.month === '1' && d.day === 1);
    const ma = days.find((d) => d.month === '8' && d.day === 15);
    if (!sf || !ma) throw new Error(`no ${sf ? 'Mid-Autumn' : 'Spring Festival'} found in ${y}`);
    spring[y] = sf.date;
    midAutumn[y] = ma.date;
  }
  return { spring, midAutumn };
}

/** The ICU table, with the published date wherever the two disagree. Every year needs one. */
function crossCheck(icu) {
  const fixed = [];
  const missing = [];
  const table = { spring: {}, midAutumn: {} };
  for (const kind of Object.keys(table)) {
    for (let y = FIRST; y <= LAST; y++) {
      const pub = PUBLISHED[kind][y];
      if (!pub) missing.push(`${kind} ${y}`);
      else if (pub !== icu[kind][y]) fixed.push(`${kind === 'spring' ? 'Spring Festival' : 'Mid-Autumn'} ${y}: ICU ${icu[kind][y]}, published ${pub}`);
      table[kind][y] = pub || icu[kind][y];
    }
  }
  return { table, fixed, missing };
}

const pyDict = (o) => `{\n${Object.entries(o).map(([y, d]) => `    ${y}: "${d}",`).join('\n')}\n}`;
const jsDict = (o) => `{\n${Object.entries(o).map(([y, d]) => `  ${y}: '${d}',`).join('\n')}\n}`;

function python(t) {
  return `"""Festival dates for the README art (idea #150): the banner shows a small touch on New Year's
Day (Jan 1), the Spring Festival (Chinese New Year) and the Mid-Autumn Festival, and nothing on
any other day.

Generated by scripts/make_holidays.mjs from Node's ICU Chinese calendar, every year checked
against published dates (Wikipedia and the Hong Kong Observatory; where ICU was a day off, in
2027 and 2030, the published date is used). Do not edit by hand. The same table is in
live/holidays.mjs. Valid ${FIRST} to ${LAST}; outside those years only New Year's Day is known.
"""
from __future__ import annotations

import datetime as dt

FIRST, LAST = ${FIRST}, ${LAST}
SPRING_FESTIVAL = ${pyDict(t.spring)}
MID_AUTUMN = ${pyDict(t.midAutumn)}


def festival_on(day: dt.date) -> str | None:
    """'new-year', 'spring-festival', 'mid-autumn' or None for a local calendar date."""
    if day.month == 1 and day.day == 1:
        return "new-year"
    d = day.isoformat()
    if SPRING_FESTIVAL.get(day.year) == d:
        return "spring-festival"
    if MID_AUTUMN.get(day.year) == d:
        return "mid-autumn"
    return None
`;
}

function module_(t) {
  return `// Festival dates (idea #150): New Year's Day (Jan 1), the Spring Festival (Chinese New Year) and
// the Mid-Autumn Festival, for the interactive page and the live banner.
// Generated by scripts/make_holidays.mjs from the ICU Chinese calendar, every year checked
// against published dates (Wikipedia and the Hong Kong Observatory). Do not edit by hand; the
// same table is in scripts/festivals.py. Valid ${FIRST} to ${LAST}. The browser's own Chinese
// calendar (Intl, ICU) is not used for other years on purpose: it puts a new moon that falls
// near midnight in Beijing on the wrong day (the Spring Festival of 2027 and 2030).

export const FIRST = ${FIRST};
export const LAST = ${LAST};
export const SPRING_FESTIVAL = ${jsDict(t.spring)};
export const MID_AUTUMN = ${jsDict(t.midAutumn)};

const pad = (n) => String(n).padStart(2, '0');

/** 'new-year', 'spring-festival', 'mid-autumn' or null for a local calendar date (month 1 to 12). */
export function festivalOn(y, m, d) {
  if (m === 1 && d === 1) return 'new-year';
  const iso = \`\${y}-\${pad(m)}-\${pad(d)}\`;
  if (SPRING_FESTIVAL[y] === iso) return 'spring-festival';
  if (MID_AUTUMN[y] === iso) return 'mid-autumn';
  return null;
}
`;
}

const { table: t, fixed, missing } = crossCheck(compute());
if (missing.length) {
  console.error(`No published date to check against: ${missing.join(', ')}. Add them to PUBLISHED.`);
  process.exit(1);
}
const checked = 2 * (LAST - FIRST + 1);
if (fixed.length) console.log(`ICU was a day off; using the published date:\n  ${fixed.join('\n  ')}`);
if (process.argv.includes('--check')) {
  const stale = [[PY, python(t)], [MJS, module_(t)]].filter(([f, text]) => {
    try { return readFileSync(f, 'utf8') !== text; } catch { return true; }
  }).map(([f]) => f);
  if (stale.length) {
    console.error(`out of date (run node scripts/make_holidays.mjs): ${stale.join(', ')}`);
    process.exit(1);
  }
  console.log(`holidays ok: ${FIRST} to ${LAST}, all ${checked} dates checked against the published tables, both files up to date`);
} else {
  writeFileSync(PY, python(t));
  writeFileSync(MJS, module_(t));
  console.log(`wrote scripts/festivals.py and live/holidays.mjs (${FIRST} to ${LAST}; all ${checked} dates checked against the published tables)`);
  for (let y = FIRST; y <= LAST; y++) console.log(`  ${y}  Spring Festival ${t.spring[y]}  Mid-Autumn ${t.midAutumn[y]}`);
}
