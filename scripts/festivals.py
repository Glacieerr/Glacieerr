"""Festival dates for the README art (idea #150): the banner shows a small touch on New Year's
Day (Jan 1), the Spring Festival (Chinese New Year) and the Mid-Autumn Festival, and nothing on
any other day.

Generated by scripts/make_holidays.mjs from Node's ICU Chinese calendar, every year checked
against published dates (Wikipedia and the Hong Kong Observatory; where ICU was a day off, in
2027 and 2030, the published date is used). Do not edit by hand. The same table is in
live/holidays.mjs. Valid 2024 to 2035; outside those years only New Year's Day is known.
"""
from __future__ import annotations

import datetime as dt

FIRST, LAST = 2024, 2035
SPRING_FESTIVAL = {
    2024: "2024-02-10",
    2025: "2025-01-29",
    2026: "2026-02-17",
    2027: "2027-02-06",
    2028: "2028-01-26",
    2029: "2029-02-13",
    2030: "2030-02-03",
    2031: "2031-01-23",
    2032: "2032-02-11",
    2033: "2033-01-31",
    2034: "2034-02-19",
    2035: "2035-02-08",
}
MID_AUTUMN = {
    2024: "2024-09-17",
    2025: "2025-10-06",
    2026: "2026-09-25",
    2027: "2027-09-15",
    2028: "2028-10-03",
    2029: "2029-09-22",
    2030: "2030-09-12",
    2031: "2031-10-01",
    2032: "2032-09-19",
    2033: "2033-09-08",
    2034: "2034-09-27",
    2035: "2035-09-16",
}


def festival_on(day: dt.date) -> str | None:
    """'new-year', 'spring-festival', 'mid-autumn' or None for a local calendar date."""
    if day.month == 1 and day.day == 1:
        return "new-year"
    d = day.isoformat()
    if SPRING_FESTIVAL.get(day.year) == d:
        return "spring-festival"
    if MID_AUTUMN.get(day.year) == d:
        return "mid-autumn"
    return None
